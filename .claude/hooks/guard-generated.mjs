#!/usr/bin/env node
// PreToolUse: refuse edits to build output and secrets.
let raw = "";
process.stdin.on("data", (c) => (raw += c));
process.stdin.on("end", () => {
  const path = (JSON.parse(raw).tool_input?.file_path ?? "").replaceAll("\\", "/");
  const rules = [
    [/(^|\/)dist\//, "Build output. Edit src/ and run `npm run build`."],
    [/(^|\/)\.env$/, "Local environment file; document new variables in the README instead."],
    [/(^|\/)package-lock\.json$/, "Changed by npm only."],
    [/deploy\/seccomp\.json$/, "Generated by deploy/make-seccomp.mjs."],
  ];
  for (const [re, why] of rules) {
    if (re.test(path)) {
      console.error(`Blocked: ${path}\n${why}`);
      process.exit(2);
    }
  }
});
